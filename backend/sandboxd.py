ARCHES = {"x86_64": (0xC000003E, DENY_X86_64, 56, 435), "aarch64": (0xC00000B7, DENY_AARCH64, 220, 435)}
CLONE_NS_FLAGS = 0x7E020080       # all CLONE_NEW*
ENOSYS, EPERM = 38, 1

BPF_LD_W_ABS, BPF_JEQ, BPF_JGE, BPF_JSET, BPF_RET = 0x20, 0x15, 0x35, 0x45, 0x06
RET_ALLOW, RET_KILL, RET_ERRNO = 0x7FFF0000, 0x80000000, 0x00050000


def seccomp_program():
    """The filter as bytes (struct sock_filter[]), or None on an unknown architecture."""
    arch = ARCHES.get(platform.machine())
    if arch is None:
        return None
    audit_arch, deny, nr_clone, nr_clone3 = arch

    def ins(code, k=0, jt=0, jf=0):
        return struct.pack("=HBBI", code, jt, jf, k)
    p = [ins(BPF_LD_W_ABS, 4),                    # seccomp_data.arch
         ins(BPF_JEQ, audit_arch, 1, 0),
         ins(BPF_RET, RET_KILL),
         ins(BPF_LD_W_ABS, 0)]                    # seccomp_data.nr
    if platform.machine() == "x86_64":            # x32 ABI numbers
        p += [ins(BPF_JGE, 0x40000000, 0, 1), ins(BPF_RET, RET_ERRNO | EPERM)]
    for nr in sorted(set(deny.values())):
        p += [ins(BPF_JEQ, nr, 0, 1), ins(BPF_RET, RET_ERRNO | EPERM)]
    # clone3 hides its flags from seccomp: ENOSYS makes libc fall back to clone
    p += [ins(BPF_JEQ, nr_clone3, 0, 1), ins(BPF_RET, RET_ERRNO | ENOSYS)]
    p += [ins(BPF_JEQ, nr_clone, 0, 3),
          ins(BPF_LD_W_ABS, 16),                  # low word of args[0], the flags
          ins(BPF_JSET, CLONE_NS_FLAGS, 0, 1),
          ins(BPF_RET, RET_ERRNO | EPERM)]
    p += [ins(BPF_RET, RET_ALLOW)]
    return b"".join(p)


class _SockFprog(ctypes.Structure):
    _fields_ = [("len", ctypes.c_ushort), ("filter", ctypes.c_char_p)]


def install_seccomp(prog):
    PR_SET_NO_NEW_PRIVS, PR_SET_SECCOMP, SECCOMP_MODE_FILTER = 38, 22, 2
    if libc.prctl(PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) != 0:
        raise OSError(ctypes.get_errno(), "no_new_privs")
    fprog = _SockFprog(len(prog) // 8, prog)
    if libc.prctl(PR_SET_SECCOMP, SECCOMP_MODE_FILTER, ctypes.byref(fprog), 0, 0) != 0:
        raise OSError(ctypes.get_errno(), "seccomp")


# --------------------------------------------------------------------------- Landlock

LL_EXECUTE, LL_WRITE, LL_READ, LL_READDIR = 0x1, 0x2, 0x4, 0x8
LL_BASE_ALL = 0x1FFF        # ABI 1: execute ... make_sym
LL_REFER, LL_TRUNCATE = 0x2000, 0x4000
NR_LL_CREATE, NR_LL_ADD, NR_LL_RESTRICT = 444, 445, 446


def landlock_abi():
    abi = libc.syscall(NR_LL_CREATE, None, 0, 1)
    return abi if abi > 0 else 0


def install_landlock(job, abi, extra):
    """Only the toolchain (read and execute) and the job directory (everything) remain accessible."""
    handled = LL_BASE_ALL | (LL_REFER if abi >= 2 else 0) | (LL_TRUNCATE if abi >= 3 else 0)
    attr = struct.pack("=Q", handled)
    fd = libc.syscall(NR_LL_CREATE, attr, len(attr), 0)
    if fd < 0:
        raise OSError(ctypes.get_errno(), "landlock create")
    try:
        def rule(path, access):
            try:
                pfd = os.open(path, os.O_PATH | os.O_CLOEXEC)
            except OSError:
                return
            try:
                if not stat.S_ISDIR(os.fstat(pfd).st_mode):
                    access &= LL_EXECUTE | LL_WRITE | LL_READ | LL_TRUNCATE
                rule_attr = struct.pack("=Qi", access, pfd)
                if libc.syscall(NR_LL_ADD, fd, 1, rule_attr, 0) != 0:
                    raise OSError(ctypes.get_errno(), "landlock rule")
            finally:
                os.close(pfd)
        for path in ro_paths(extra):
            rule(path, LL_EXECUTE | LL_READ | LL_READDIR)
        rule("/dev/null", LL_READ | LL_WRITE | (LL_TRUNCATE if abi >= 3 else 0))
        for dev in ("/dev/zero", "/dev/urandom", "/dev/random"):
            rule(dev, LL_READ)
        rule(job, handled)
        if libc.syscall(NR_LL_RESTRICT, fd, 0) != 0:
            raise OSError(ctypes.get_errno(), "landlock restrict")
    finally:
        os.close(fd)


# --------------------------------------------------------------------------- sandbox setup

def ro_paths(extra=()):
    paths = ["/usr", "/bin", "/lib", "/lib64", "/sbin", "/etc/ld.so.cache", "/etc/alternatives", str(BACKEND)]
    if "yosys" in extra:
        paths += [str(VENV), str(UV_PYTHON), str(YOWASP_CACHE)]
    return paths


def bwrap_prefix(job, rel, env, seccomp_fd, extra):
    a = [BWRAP, "--unshare-all", "--new-session", "--die-with-parent", "--cap-drop", "ALL",
         "--clearenv"]
    for k, v in env.items():
        a += ["--setenv", k, v]
    for p in ro_paths(extra):
        if os.path.islink(p):                       # merged /usr: /bin -> usr/bin
            a += ["--symlink", os.readlink(p), p]
        elif os.path.exists(p):
            a += ["--ro-bind", p, p]
    # No --proc: a new /proc cannot be mounted in a container whose /proc has masked paths.
    a += ["--dev", "/dev", "--tmpfs", "/tmp", "--bind", str(job), JOB_DIR_INSIDE,
          "--chdir", os.path.join(JOB_DIR_INSIDE, rel) if rel else JOB_DIR_INSIDE]
    if seccomp_fd is not None:
        a += ["--seccomp", str(seccomp_fd)]
    return a + ["--"]


def job_env(job_path, extra_env, extra=()):
    env = {"PATH": PATH_ENV, "HOME": job_path, "TMPDIR": job_path, "LANG": "C.UTF-8"}
    if "yosys" in extra:
        env["XDG_CACHE_HOME"] = str(YOWASP_CACHE)    # compiled when the image was built
        # Otherwise YoWASP gives yosys every directory of / and the parents of the working one.
        env["YOWASP_MOUNT"] = "/=."
    for k, v in (extra_env or {}).items():
        if re.fullmatch(r"FPGAEMU_[A-Z_]+", str(k)) and re.fullmatch(r"\w*", str(v)):
            env[k] = str(v)
    return env


def set_limits(profile):
    lim = PROFILES[profile]
    def setl(what, value):
        resource.setrlimit(what, (value, value))
    setl(resource.RLIMIT_CPU, lim["cpu"])
    setl(resource.RLIMIT_FSIZE, lim["fsize"])
    setl(resource.RLIMIT_NOFILE, 256)
    setl(resource.RLIMIT_CORE, 0)
    setl(resource.RLIMIT_NPROC, NPROC)
    if lim["mem"] is not None:
        setl(resource.RLIMIT_AS, lim["mem"])


def spawn(mode, job, rel, profile, argv, env, stdin=subprocess.DEVNULL):
    """Starts argv in the sandbox. job: its directory; rel: the working directory inside it."""
    extra = PROFILES[profile]["extra"]
    prog = seccomp_program()
    pass_fds = ()
    seccomp_fd = None
    if mode == "bwrap":
        cmd = None
        if prog is not None:
            seccomp_fd = os.memfd_create("seccomp")
            os.write(seccomp_fd, prog)
            os.lseek(seccomp_fd, 0, os.SEEK_SET)
            pass_fds = (seccomp_fd,)
        cmd = bwrap_prefix(job, rel, job_env(JOB_DIR_INSIDE, env, extra), seccomp_fd, extra) + argv
        cwd, run_env = "/", {"PATH": PATH_ENV}
    else:
        cmd = argv
        cwd, run_env = os.path.join(job, rel) if rel else str(job), job_env(str(job), env, extra)
    abi = landlock_abi()

    def setup():
        libc.prctl(1, int(signal.SIGKILL), 0, 0, 0)     # PR_SET_PDEATHSIG: dies with this handler
        set_limits(profile)
        if mode != "bwrap":
            libc.prctl(38, 1, 0, 0, 0)                  # PR_SET_NO_NEW_PRIVS, required by Landlock
            if abi:
                install_landlock(str(job), abi, extra)
            install_seccomp(prog)     # last: forbids what the steps above need

    try:
        return subprocess.Popen(cmd, cwd=cwd, env=run_env, stdin=stdin, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                start_new_session=True, preexec_fn=setup, pass_fds=pass_fds, umask=0o007)
    finally:
        if seccomp_fd is not None:
            os.close(seccomp_fd)


def killjob(proc):
    # bwrap: killing it kills the PID namespace (--die-with-parent).
    # fallback: the job cannot leave its process group (setsid/setpgid are denied).
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except OSError:
        pass


# --------------------------------------------------------------------------- self-test

STATE = {"mode": None, "reason": "", "tests": {}}


def run_probe(mode, argv):
    with tempfile.TemporaryDirectory(prefix="selftest-", dir=_selftest_dir()) as d:
        os.chmod(d, 0o770)
        p = spawn(mode, d, "", "tool", argv, {})
        try:
            out, err = p.communicate(timeout=20)
        except subprocess.TimeoutExpired:
            killjob(p)
            p.communicate()
            return -1, "timeout"
        return p.returncode, (out + err).decode("utf-8", "replace")


def _selftest_dir():
    return tempfile.gettempdir()


# Run with a Python that sees nothing of the app: is the sandbox enforced in this mode?
PROBE_NET = ("import socket\n"
             "try:\n    socket.socket(socket.AF_INET, socket.SOCK_STREAM); print('OPEN')\n"
             "except OSError:\n    print('BLOCKED')\n")
PROBE_FS = ("try:\n    open('/etc/passwd').read(); print('OPEN')\n"
            "except OSError:\n    print('BLOCKED')\n")


def verify_mode(mode):
    """{test: True if the protection is in place}. /etc/passwd is world-readable, so whether it can
    be read tells whether the filesystem view is restricted."""
    py = "/usr/bin/python3"
    tests = {}
    rc, out = run_probe(mode, ["/bin/true"])
    tests["runs"] = rc == 0
    if not tests["runs"]:
        return tests, out.strip()[-300:]
    rc, out = run_probe(mode, [py, "-S", "-c", PROBE_NET])
    tests["no_network"] = "BLOCKED" in out
    rc, out = run_probe(mode, [py, "-S", "-c", PROBE_FS])
    tests["restricted_filesystem"] = "BLOCKED" in out
    return tests, ""


def choose_mode():
    if MODE in ("auto", "bwrap") and os.path.exists(BWRAP):
        tests, why = verify_mode("bwrap")
        if tests.get("runs") and tests.get("no_network") and tests.get("restricted_filesystem"):
            STATE.update(mode="bwrap", reason="namespaces available", tests=tests)
            return
        STATE["bwrap_error"] = why or str(tests)
    if MODE == "bwrap":
        STATE.update(mode=None, reason="FPGAEMU_SANDBOX_MODE=bwrap, and bwrap does not work here")
        return
    if seccomp_program() is None:
        STATE.update(mode=None, reason=f"fallback mode has no seccomp filter for {platform.machine()}")
        return
    tests, why = verify_mode("fallback")
    if tests.get("runs") and tests.get("no_network"):
        abi = landlock_abi()
        STATE.update(mode="fallback", tests=tests, landlock_abi=abi,
                     reason="namespaces blocked by the container configuration or the kernel"
                     + ("" if abi else "; Landlock unavailable, only file permissions limit reads"))
        return
    STATE.update(mode=None, tests=tests, reason=f"no mode could be enforced: {why or tests}")


# --------------------------------------------------------------------------- requests

def send_frame(conn, kind, data=b""):
    conn.sendall(kind + struct.pack("=I", len(data)) + data)


def read_request(conn):
    conn.settimeout(5)
    buf = b""
    while b"\n" not in buf:
        d = conn.recv(65536)
        if not d:
            raise ValueError("closed")
        buf += d
        if len(buf) > 1024 * 1024:
            raise ValueError("too large")
    conn.settimeout(None)
    return json.loads(buf.split(b"\n", 1)[0])


def job_path(token):
    if not isinstance(token, str) or not TOKEN_RE.fullmatch(token):
        raise ValueError("bad token")
    path = JOBS_ROOT / token
    if not stat.S_ISDIR(os.lstat(path).st_mode):
        raise ValueError("not a directory")
    return path


def valid_rel(rel):
    if not isinstance(rel, str) or rel.startswith("/") or ".." in rel.split("/") or "\0" in rel:
        raise ValueError("bad directory")
    return rel


def do_run(conn, req):
    profile = req.get("profile")
    if profile not in PROFILES:
        raise ValueError("bad profile")
    if STATE["mode"] is None:
        send_frame(conn, b"X", json.dumps({"rc": None, "reason": "sandbox unavailable"}).encode())
        return
    argv = req.get("argv")
    if not (isinstance(argv, list) and argv and all(isinstance(a, str) and "\0" not in a for a in argv)):
        raise ValueError("bad argv")
    job, rel = job_path(req.get("token")), valid_rel(req.get("rel", ""))
    discard = bool(req.get("discard"))
    limit = PROFILES[profile]
    wall = min(float(req.get("timeout") or limit["wall"]), limit["wall"])
    try:
        proc = spawn(STATE["mode"], job, rel, profile, argv, req.get("env"))
    except (OSError, subprocess.SubprocessError) as e:
        send_frame(conn, b"X", json.dumps({"rc": None, "reason": f"could not start (errno {getattr(e, 'errno', '?')})"}).encode())
        return
    try:
        conn.settimeout(60)       # a client that stops reading cannot hold the job past its limit
        send_frame(conn, b"S")
        pump(conn, proc, wall, discard)
    finally:
        killjob(proc)


def pump(conn, proc, wall, discard):
    streams = {proc.stdout.fileno(): b"O", proc.stderr.fileno(): b"E"}
    for fd in streams:
        os.set_blocking(fd, False)
    deadline = time.monotonic() + wall
    total = 0
    reason = None
    client_gone = False
    while True:
        left = deadline - time.monotonic()
        if left <= 0:
            reason = "time limit"
            break
        r, _, _ = select.select(list(streams) + [conn], [], [], min(left, 0.5))
        if conn in r:
            try:
                if not conn.recv(4096):
                    client_gone = True
                    reason = "stopped"
                    break
            except OSError:
                client_gone = True
                reason = "stopped"
                break
        for fd in [f for f in r if f in streams]:
            try:
                data = os.read(fd, 65536)
            except BlockingIOError:
                continue
            if not data:
                del streams[fd]
                continue
            if discard:
                continue
            total += len(data)
            if total > MAX_OUTPUT:
                reason = "output limit"
                break
            send_frame(conn, streams[fd], data)
        if reason:
            break
        if not streams or proc.poll() is not None:
            # The main process ended: take what is already in the pipes, background processes go.
            for fd, kind in streams.items():
                try:
                    data = os.read(fd, MAX_OUTPUT)
                    if data and not discard:
                        send_frame(conn, kind, data)
                except OSError:
                    pass
            break
    killjob(proc)
    rc = proc.wait()
    if not client_gone:
        send_frame(conn, b"X", json.dumps({"rc": rc, "reason": reason}).encode())


def do_cleanup(conn, req):
    """Removes what a job left in its directory: a job can make its files inaccessible to the web
    app (chmod), and only their owner, this user, can undo that."""
    job = job_path(req.get("token"))
    with os.scandir(job) as it:
        entries = list(it)
    def opened(path):
        try:                    # fails on what the web app owns: it removes that itself
            os.chmod(path, 0o770)
        except OSError:
            pass
    for e in entries:
        try:
            if not e.is_dir(follow_symlinks=False):
                os.unlink(e.path)
                continue
            opened(e.path)
            for d, dirs, _ in os.walk(e.path):       # top-down: opens each level before entering
                for n in dirs:
                    p = os.path.join(d, n)
                    if not os.path.islink(p):
                        opened(p)
            shutil.rmtree(e.path, ignore_errors=True)
        except OSError:
            pass
    send_frame(conn, b"X", b'{"rc": 0}')


def do_killpid(conn, req):
    """For the admin page: kills a process of this user, except this service."""
    pid = req.get("pid")
    allowed = isinstance(pid, int) and pid > 1 and pid not in (os.getpid(), os.getppid(), MAIN_PID)
    rc = 1
    if allowed:
        try:
            if os.stat(f"/proc/{pid}").st_uid == os.getuid():
                os.kill(pid, signal.SIGKILL)
                rc = 0
        except OSError:
            pass
    send_frame(conn, b"X", json.dumps({"rc": rc}).encode())


def handle(conn):
    try:
        req = read_request(conn)
        op = req.get("op")
        if op == "run":
            do_run(conn, req)
        elif op == "cleanup":
            do_cleanup(conn, req)
        elif op == "killpid":
            do_killpid(conn, req)
        elif op == "status":
            send_frame(conn, b"X", json.dumps(STATE).encode())
        else:
            raise ValueError("bad op")
    except (ValueError, KeyError, TypeError, OSError) as e:
        try:
            send_frame(conn, b"X", json.dumps({"rc": None, "reason": f"bad request: {type(e).__name__}"}).encode())
        except OSError:
            pass


MAIN_PID = os.getpid()


def serve():
    try:
        choose_mode()
    except Exception as e:     # refuse jobs, and tell why, rather than restart in a loop
        STATE.update(mode=None, reason=f"self-test failed: {type(e).__name__}: {e}")
    print(f"sandboxd: mode={STATE['mode']} ({STATE['reason']}) tests={STATE['tests']}", flush=True)
    SOCKET_PATH.parent.mkdir(parents=True, exist_ok=True)
    try:
        SOCKET_PATH.unlink()
    except FileNotFoundError:
        pass
    srv = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    old = os.umask(0o117)         # socket file 0660: only this user and the group of the directory
    srv.bind(str(SOCKET_PATH))
    os.umask(old)
    srv.listen(128)
    signal.signal(signal.SIGTERM, lambda *a: sys.exit(0))
    children = set()
    while True:
        conn, _ = srv.accept()
        for pid in list(children):
            try:
                if os.waitpid(pid, os.WNOHANG)[0]:
                    children.discard(pid)
            except ChildProcessError:
                children.discard(pid)
        if len(children) >= MAX_JOBS:
            try:
                send_frame(conn, b"X", json.dumps({"rc": None, "reason": "too many jobs"}).encode())
            except OSError:
                pass
            conn.close()
            continue
        pid = os.fork()
        if pid == 0:
            srv.close()
            signal.signal(signal.SIGTERM, signal.SIG_DFL)
            try:
                handle(conn)
            finally:
                os._exit(0)
        children.add(pid)
        conn.close()


if __name__ == "__main__":
    if os.geteuid() == 0:
        sys.exit("sandboxd must not run as root.")
    serve()
