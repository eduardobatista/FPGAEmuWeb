#!/usr/bin/env python3
"""Runs the code sent by users (ghdl, the binaries it builds, yosys, ghwdump) in a sandbox.

Runs as the unprivileged user fpgarun, which owns nothing and cannot read work/ nor any key; the
web app talks to it through a Unix socket. Closing the socket kills the job, which is how the web
app (another user, so it cannot signal the job) stops it. No privilege is needed here: no setuid.

Modes, chosen by a self-test at start (FPGAEMU_SANDBOX_MODE=auto|bwrap|fallback):
  bwrap     namespaces: own mount/PID/network/IPC/UTS view with only the toolchain and the job
            directory. Needs a container whose seccomp profile allows them (deploy/README.md).
  fallback  no namespaces (default Docker profile): the separate uid, Landlock (file access) and a
            seccomp filter (no sockets, no ptrace...). Weaker: jobs share the PID space, and without
            Landlock only file permissions limit what can be read. Reported in the diagnostics.
If the mode cannot be enforced, jobs are refused: nothing ever runs without a sandbox.

Stdlib only; start it with a clean environment (see supervisord.conf). Names of users never reach
this process: jobs are identified by a random token. Do not log anything from the requests.
"""

